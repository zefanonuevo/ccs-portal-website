#!/usr/bin/env bash
# Builds an Apache config that restores each visitor's real address when the site is behind Cloudflare.
#
# Why: Cloudflare connects to the VM, so without this the server sees Cloudflare's addresses for everyone.
# The sign-in rate limit and the audit log would then treat all visitors on one Cloudflare address as one person.
#
# How it works: Apache's mod_remoteip trusts the CF-Connecting-IP header ONLY when the connection comes from a
# Cloudflare address (the list this script writes). A request that reaches the VM from anywhere else cannot fake it.
#
# Usage (on the VM):
#   sudo bash server/deploy/cloudflare-remoteip.sh            # writes /etc/apache2/conf-available/cloudflare-remoteip.conf
#   sudo a2enmod remoteip && sudo a2enconf cloudflare-remoteip
#   sudo apache2ctl configtest && sudo systemctl reload apache2
# Cloudflare changes its list rarely. Run the script again (and reload Apache) now and then, for example every few months.
#
# Testing: set CF_SRC_DIR to a folder holding files named ips-v4 and ips-v6 to read the lists from there instead of the web.
set -euo pipefail

OUT="${1:-/etc/apache2/conf-available/cloudflare-remoteip.conf}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

fetch() { # $1 = v4 or v6
  if [ -n "${CF_SRC_DIR:-}" ]; then cp "$CF_SRC_DIR/ips-$1" "$TMP/raw-$1"
  else curl -fsS --max-time 20 "https://www.cloudflare.com/ips-$1" -o "$TMP/raw-$1"; fi
  tr -d '\r' < "$TMP/raw-$1" | sed 's/[[:space:]]*$//' | grep -v '^$' > "$TMP/$1" || true
}
fetch v4
fetch v6

# Accept only lines that look like network ranges. Anything else means the download is wrong: stop and write nothing.
bad4=$(grep -v -E '^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$' "$TMP/v4" || true)
bad6=$(grep -v -E '^[0-9A-Fa-f:]+/[0-9]{1,3}$' "$TMP/v6" || true)
if [ -n "$bad4$bad6" ]; then echo "Unexpected lines in the address lists, nothing written:" >&2; echo "$bad4$bad6" >&2; exit 1; fi
n4=$(wc -l < "$TMP/v4"); n6=$(wc -l < "$TMP/v6")
if [ "$n4" -lt 5 ] || [ "$n6" -lt 3 ]; then echo "Address lists look too short (v4: $n4, v6: $n6), nothing written." >&2; exit 1; fi

{
  echo "# Generated by server/deploy/cloudflare-remoteip.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not edit by hand."
  echo "# Cloudflare ranges: $n4 IPv4, $n6 IPv6. Applies to every site on this Apache, but only for connections from these addresses."
  echo "RemoteIPHeader CF-Connecting-IP"
  while read -r r; do echo "RemoteIPTrustedProxy $r"; done < "$TMP/v4"
  while read -r r; do echo "RemoteIPTrustedProxy $r"; done < "$TMP/v6"
} > "$TMP/out.conf"

install -m 644 "$TMP/out.conf" "$OUT"
echo "Wrote $OUT ($n4 IPv4 and $n6 IPv6 ranges)."
echo "Next: sudo a2enmod remoteip && sudo a2enconf cloudflare-remoteip && sudo apache2ctl configtest && sudo systemctl reload apache2"
